function exactText(text: string): string {
  return textMap[text] || text
}

function translateDynamicText(text: string): string | null {
  let m = text.match(/^(.+)异动导致(.+)(上升|下降)：传导强度([+-]?\d+(?:\.\d+)?)，预计从([\d.,-]+)变为([\d.,-]+)(.*)$/)
  if (m) {
    const direction = m[3] === '上升' ? 'rises' : 'falls'
    const unit = m[7] ? ` ${m[7]}` : ''
    return `${exactText(m[1])} shock drives ${exactText(m[2])} ${direction}; transmission strength ${m[4]}, estimated from ${m[5]} to ${m[6]}${unit}.`
  }

  m = text.match(/^当前利率([\d.]+)%，可降息约([\d.]+)次（每次25bp），(.+)$/)
  if (m) return `Current rate is ${m[1]}%; roughly ${m[2]} 25 bp cuts are available, ${exactText(m[3])}.`

  m = text.match(/^当前([\d.]+)万亿美元，(.+)$/)
  if (m) return `Current balance sheet is $${m[1]}tn, ${exactText(m[2])}.`

  m = text.match(/^当前利差([-\d.]+)%，(.+)$/)
  if (m) return `Current spread is ${m[1]}%, ${exactText(m[2])}.`

  m = text.match(/^当前([\d.]+)%，(.+)$/)
  if (m) return `Current level is ${m[1]}%, ${exactText(m[2])}.`

  m = text.match(/^1年期LPR ([\d.]+)%，(.+)$/)
  if (m) return `1Y LPR is ${m[1]}%, ${exactText(m[2])}.`

  m = text.match(/^当前([\d.]+)，(.+)$/)
  if (m) return `Current reading is ${m[1]}, ${exactText(m[2])}.`

  return null
}

function translateText(value: unknown): string {
  if (value === null || value === undefined) return ''
  const text = String(value)
  if (currentLang.value === 'zh') return text
  if (textMap[text]) return textMap[text]
  const dynamic = translateDynamicText(text)
  if (dynamic) return dynamic

  let translated = text
  const keys = Object.keys(textMap).sort((a, b) => b.length - a.length)
  for (const key of keys) {
    translated = translated.split(key).join(textMap[key])
  }
  return translated
}

function pickLang(obj: any, zhKey = 'name_zh', enKey = 'name_en', fallbackKey = 'name'): string {
  if (!obj) return ''
  if (currentLang.value === 'en') return obj[enKey] || translateText(obj[fallbackKey] || obj[zhKey] || '')
  return obj[zhKey] || obj[fallbackKey] || obj[enKey] || ''
}

export function useI18n() {
  function t(key: string, params?: Record<string, any>): string {
    let text = messages[key]?.[currentLang.value] || messages[key]?.['zh'] || key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(`{${k}}`, String(v))
      }
    }
    return text
  }

  function setLang(lang: 'zh' | 'en') {
    currentLang.value = lang
    if (typeof window !== 'undefined') {
      localStorage.setItem('gfcri_lang', lang)
    }
  }

  function toggleLang() {
    setLang(currentLang.value === 'zh' ? 'en' : 'zh')
  }

  return {
    lang: computed(() => currentLang.value),
    t,
    tx: translateText,
    pickLang,
    setLang,
    toggleLang,
  }
}
